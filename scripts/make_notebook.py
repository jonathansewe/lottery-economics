"""Regenerate notebooks/analysis.ipynb (then execute it with nbconvert, see README)."""
from pathlib import Path

import nbformat as nbf

md, code = nbf.v4.new_markdown_cell, nbf.v4.new_code_cell
cells = [
    md("# Lottery Economics — analysis notebook\n\n"
       "Walks through the same computations the website shows, using the `lottery` package. "
       "Re-run after `python -m lottery.ingest` to fill in the real-data sections.\n\n"
       "**Nothing here predicts numbers.** The point is the opposite: to show that apparent "
       "patterns are what fair randomness looks like."),
    code("import sys, pathlib\n"
         "sys.path.insert(0, str(pathlib.Path.cwd().parent))  # run from notebooks/\n"
         "import numpy as np, pandas as pd, matplotlib.pyplot as plt\n"
         "from lottery import rules, stats, config\n"
         "from lottery import math as lm\n"
         "pd.set_option('display.width', 120)\n"
         "data = {g: stats.load_draws(g) for g in rules.GAMES}\n"
         "{g: (None if d is None else len(d)) for g, d in data.items()}"),
    md("## 1. Exact odds\nEach tier's probability by counting combinations; compare with the published odds."),
    code("rows = []\n"
         "for g in ('powerball', 'mega_millions'):\n"
         "    era = rules.current_era(g)\n"
         "    for r in lm.odds_table(era):\n"
         "        rows.append({'game': era.label, 'match': f\"{r['white']}+{r['special']}\", 'prize': r['prize'],\n"
         "                     '1 in (exact)': round(r['one_in'], 2), '1 in (official)': r['official_one_in']})\n"
         "pd.DataFrame(rows)"),
    md("## 2. Expected value per $1\nFrom the advertised number down to what a NYC resident actually expects back."),
    code("rows = []\n"
         "for g in ('powerball', 'mega_millions'):\n"
         "    era = rules.current_era(g)\n"
         "    for J, N in [(era.starting_jackpot, 10e6), (1e9, 200e6)]:\n"
         "        ev = lm.ev_breakdown(era, J, tickets_sold=N)\n"
         "        rows.append({'game': era.label, 'jackpot': f'${J/1e6:,.0f}M', 'tickets (assumed)': f'{N/1e6:.0f}M',\n"
         "                     **{s: round(ev[s]['total_per_dollar'], 3) for s in ('advertised', 'cash', 'after_tax', 'with_split')}})\n"
         "pd.DataFrame(rows)"),
    md("## 2b. Every New York game\nEV per $1 before tax, after tax owed, and after withholding only. "
       "Values flagged `verified=False` use prize amounts not confirmed from an official page."),
    code("rows = []\n"
         "for g in rules.GAMES:\n"
         "    if g in ('powerball', 'mega_millions'):\n"
         "        continue\n"
         "    era = rules.current_era(g)\n"
         "    for owed, wh in zip(lm.game_ev(era, 'owed'), lm.game_ev(era, 'withholding')):\n"
         "        rows.append({'game': rules.GAME_LABELS[g], 'play': owed['play'], 'pre_tax': round(owed['pre_tax'], 3),\n"
         "                     'after_tax_owed': round(owed['after_tax'], 3), 'after_withholding': round(wh['after_tax'], 3),\n"
         "                     'verified': owed['verified']})\n"
         "pd.DataFrame(rows)"),
    md("## 3. Why the chi-square needs a correction\n"
       "A draw takes 5 *distinct* balls, so counts are negatively correlated and the plain Pearson "
       "statistic averages m−k instead of m−1. Multiplying by (m−1)/(m−k) fixes it."),
    code("rng = np.random.default_rng(0)\n"
         "m, k, n = 69, 5, 500\n"
         "raw = np.array([stats.chi_square(stats.simulate_counts(n, k, m, rng), n, k, m)['statistic_raw'] for _ in range(3000)])\n"
         "print(f'mean raw X^2 = {raw.mean():.1f}  (theory m-k = {m-k})')\n"
         "print(f'mean corrected = {(raw*(m-1)/(m-k)).mean():.1f}  (theory m-1 = {m-1})')"),
    md("## 4. Fair data has hot and cold numbers too\n"
       "1,000 perfectly fair Powerball draws, generated by a seeded RNG."),
    code("sim = stats.simulate_fair(rules.current_era('powerball'), 1000, histories=1000)\n"
         "ex = sim['example']\n"
         "fig, ax = plt.subplots(figsize=(12, 3))\n"
         "ax.bar(ex['labels'], ex['counts'], color='#8aa')\n"
         "ax.axhline(sim['expected'], color='k', lw=1)\n"
         "ax.axhspan(*sim['band95'], color='k', alpha=.08)\n"
         "ax.set_title(f\"Fair simulation: hottest {ex['hot']}, coldest {ex['cold']}, spread {ex['spread']}\")\n"
         "plt.show()\n"
         "print('spread (max-min) over 1,000 fair histories: 5th pct', sim['spread']['p05'], 'median', sim['spread']['median'], '95th', sim['spread']['p95'])\n"
         "print('share of fair histories with chi-square p < 0.05:', sim['p_values']['share_below_005'])\n"
         "print('mean first-half vs second-half rank correlation:', round(sim['persistence']['mean'], 4))"),
    md("## 5. Real draws: frequencies and chi-square (per era, never pooled)"),
    code("res = stats.analyze()\n"
         "if not res['tests']:\n"
         "    print('No data in data/ yet. Run: python -m lottery.ingest')\n"
         "else:\n"
         "    cols = ['game', 'era_label', 'ball_set', 'n_draws', 'statistic', 'df', 'p_value', 'p_bonferroni', 'significant']\n"
         "    display(pd.DataFrame(res['tests'])[cols])"),
    code("for f in res['frequencies']:\n"
         "    if f['ball_set'] not in ('white', 'special') or f['era_id'] not in ('pb_2015', 'mm_2025'):\n"
         "        continue\n"
         "    fig, ax = plt.subplots(figsize=(12, 2.5))\n"
         "    ax.bar(f['labels'], f['counts'], color='#a88')\n"
         "    ax.axhline(f['expected'], color='k', lw=1); ax.axhspan(*f['band95'], color='k', alpha=.08)\n"
         "    ax.set_title(f\"{f['era_label']} — {f['ball_set']} ({f['n_draws']} draws); outside 95% band: {f['outside_band']} (expect ~{f['expected_outside']})\")\n"
         "    plt.show()"),
    md("## 6. Real data vs. fair simulation"),
    code("for s in stats.simulation_report(histories=500):\n"
         "    if s['real']:\n"
         "        r = s['real']\n"
         "        print(f\"{s['era_label']}: spread {r['spread']} is at the {r['spread_percentile']:.0f}th percentile of fair data; \"\n"
         "              f\"half-to-half correlation {r['persistence']:.3f} (fair 90% range {r['fair_persistence_p05_p95']})\")\n"
         "    else:\n"
         "        print(f\"{s['era_label']}: no real data yet\")"),
]
nb = nbf.v4.new_notebook(cells=cells, metadata={"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"}})
out = Path(__file__).resolve().parent.parent / "notebooks" / "analysis.ipynb"
nbf.write(nb, out)
